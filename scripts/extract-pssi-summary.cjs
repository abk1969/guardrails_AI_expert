#!/usr/bin/env node
/*
 * scripts/extract-pssi-summary.cjs
 *
 * Regenerate the <PSSI_SUMMARY_BEGIN>..<PSSI_SUMMARY_END> block in
 * api/v1/chatbot/send.ts. The Vercel serverless function cannot import
 * arbitrary TS/JSON from outside api/ reliably (cf commit 9f72e0d), so
 * a compact summary of the 172 PSSI IA v3 rules is inlined.
 *
 * Input  : data_ai_risk/extracted/pssi-ia-v3.json
 * Output : api/v1/chatbot/send.ts (inline replacement between markers)
 */

'use strict';

const fs = require('fs');
const path = require('path');

const REPO_ROOT = path.resolve(__dirname, '..');
const INPUT_JSON = path.join(REPO_ROOT, 'data_ai_risk', 'extracted', 'pssi-ia-v3.json');
const TARGET_TS = path.join(REPO_ROOT, 'api', 'v1', 'chatbot', 'send.ts');

const BEGIN = '// <PSSI_SUMMARY_BEGIN>';
const END = '// <PSSI_SUMMARY_END>';

function buildInlineBlock(data) {
  const summary = data.rules.map((r) => ({
    id: r.id,
    chapterNumber: r.chapterNumber,
    ruleText: (r.ruleText || '').slice(0, 260),
  }));

  const chapterIndex = data.chapters
    .filter((c) => Array.isArray(c.rules) && c.rules.length > 0)
    .map((c) => ({
      number: c.number,
      title: c.title,
      count: c.rules.length,
    }));

  const lines = [];
  lines.push(BEGIN);
  lines.push('// AUTO-GENERATED by scripts/extract-pssi-summary.cjs — do not edit manually.');
  lines.push('// Regenerate: node scripts/extract-pssi-summary.cjs');
  lines.push('// Source: data_ai_risk/PSSI_IA_v3_CONSOLIDE.pdf (172 exigences SIA-001..SIA-172).');
  lines.push('interface PssiSummaryItem { id: string; chapterNumber: string; ruleText: string; }');
  lines.push('interface PssiChapterIndex { number: string; title: string; count: number; }');
  lines.push('const PSSI_SUMMARY: PssiSummaryItem[] = ' + JSON.stringify(summary, null, 2) + ';');
  lines.push('const PSSI_CHAPTERS: PssiChapterIndex[] = ' + JSON.stringify(chapterIndex, null, 2) + ';');
  lines.push('const PSSI_VERSION = ' + JSON.stringify(data.meta.version) + ';');
  lines.push('const PSSI_TOTAL_RULES = ' + data.meta.totalRules + ';');
  lines.push(END);
  return lines.join('\n');
}

function main() {
  const data = JSON.parse(fs.readFileSync(INPUT_JSON, 'utf8'));
  const block = buildInlineBlock(data);

  let ts = fs.readFileSync(TARGET_TS, 'utf8');

  if (ts.includes(BEGIN) && ts.includes(END)) {
    const before = ts.slice(0, ts.indexOf(BEGIN));
    const after = ts.slice(ts.indexOf(END) + END.length);
    ts = before + block + after;
  } else {
    // Insert just before the first `export default` or at file start.
    const insertPoint = ts.indexOf('export default');
    if (insertPoint === -1) {
      ts = block + '\n\n' + ts;
    } else {
      ts = ts.slice(0, insertPoint) + block + '\n\n' + ts.slice(insertPoint);
    }
  }

  fs.writeFileSync(TARGET_TS, ts, 'utf8');
  console.log(`Inlined ${data.meta.totalRules} PSSI rules + ${data.chapters.filter((c) => c.rules.length > 0).length} chapters into ${path.relative(REPO_ROOT, TARGET_TS)}`);
}

main();
